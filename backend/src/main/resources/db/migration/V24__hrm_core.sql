CREATE TABLE leave_balances (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id      BIGINT       NOT NULL REFERENCES employees(id),
    leave_type_id    BIGINT       NOT NULL REFERENCES leave_types(id),
    balance_year     INT          NOT NULL,
    entitled         NUMERIC(5,1) NOT NULL DEFAULT 0 CHECK (entitled >= 0),
    carried_forward  NUMERIC(5,1) NOT NULL DEFAULT 0 CHECK (carried_forward >= 0),
    used             NUMERIC(5,1) NOT NULL DEFAULT 0 CHECK (used >= 0),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by       BIGINT,
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by       BIGINT,
    version          BIGINT       NOT NULL DEFAULT 0,
    company_id       BIGINT       NOT NULL DEFAULT 1,
    CONSTRAINT uq_leave_balance UNIQUE (employee_id, leave_type_id, balance_year)
);

CREATE TABLE leave_applications (
    id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    application_number  VARCHAR(20)  NOT NULL,
    employee_id         BIGINT       NOT NULL REFERENCES employees(id),
    leave_type_id       BIGINT       NOT NULL REFERENCES leave_types(id),
    from_date           DATE         NOT NULL,
    to_date             DATE         NOT NULL,
    half_day            BOOLEAN      NOT NULL DEFAULT FALSE,
    days                NUMERIC(4,1) NOT NULL CHECK (days > 0),
    reason              VARCHAR(300),
    status              VARCHAR(10)  NOT NULL DEFAULT 'PENDING'
                            CHECK (status IN ('PENDING','APPROVED','REJECTED','CANCELLED')),
    decided_by          BIGINT       REFERENCES users(id),
    decided_at          TIMESTAMPTZ,
    decision_reason     VARCHAR(300),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    version             BIGINT       NOT NULL DEFAULT 0,
    company_id          BIGINT       NOT NULL DEFAULT 1,
    CONSTRAINT uq_leave_applications_number UNIQUE (application_number),
    CONSTRAINT chk_leave_dates CHECK (to_date >= from_date)
);
CREATE INDEX ix_leave_employee ON leave_applications (employee_id, from_date);
CREATE INDEX ix_leave_status   ON leave_applications (status);

-- DESIGN section 19.1 names training_records but defines no columns; shaped from HRM-006
-- (programmes, attendance, certifications, renewal dates).
CREATE TABLE training_records (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT       NOT NULL REFERENCES employees(id),
    programme_name  VARCHAR(150) NOT NULL,
    training_type   VARCHAR(20)  NOT NULL CHECK (training_type IN ('INTERNAL','EXTERNAL','CERTIFICATION','ON_THE_JOB')),
    provider        VARCHAR(120),
    start_date      DATE         NOT NULL,
    end_date        DATE,
    hours           NUMERIC(6,2) CHECK (hours >= 0),
    status          VARCHAR(12)  NOT NULL DEFAULT 'PLANNED'
                        CHECK (status IN ('PLANNED','COMPLETED','NO_SHOW','CANCELLED')),
    score           NUMERIC(5,2),
    certificate_no  VARCHAR(40),
    certified_on    DATE,
    renewal_due_on  DATE,
    notes           VARCHAR(300),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      BIGINT,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by      BIGINT,
    version         BIGINT       NOT NULL DEFAULT 0,
    company_id      BIGINT       NOT NULL DEFAULT 1,
    CONSTRAINT chk_training_dates CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX ix_training_employee ON training_records (employee_id);
CREATE INDEX ix_training_renewal  ON training_records (renewal_due_on) WHERE renewal_due_on IS NOT NULL;

