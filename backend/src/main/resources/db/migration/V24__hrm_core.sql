CREATE TABLE employees (
    id                      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_code           VARCHAR(20)   NOT NULL,
    user_id                 BIGINT        REFERENCES users(id),
    first_name              VARCHAR(60)   NOT NULL,
    last_name               VARCHAR(60)   NOT NULL,
    email                   VARCHAR(160),
    phone                   VARCHAR(20),
    designation             VARCHAR(80),
    department              VARCHAR(60),
    plant_id                BIGINT        REFERENCES plants(id),
    cost_centre_id          BIGINT        REFERENCES cost_centres(id),
    date_of_joining         DATE          NOT NULL,
    date_of_leaving         DATE,
    employment_type         VARCHAR(15)   NOT NULL CHECK (employment_type IN ('PERMANENT','CONTRACT','TRAINEE')),
    pay_grade               VARCHAR(10),
    basic_pay               NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (basic_pay >= 0),
    fixed_travel_allowance  NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (fixed_travel_allowance >= 0),
    fixed_other_allowances  NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (fixed_other_allowances >= 0),
    bank_account_no         VARCHAR(30),
    bank_ifsc               VARCHAR(15),
    pf_number               VARCHAR(20),
    esi_number              VARCHAR(20),
    default_shift           VARCHAR(10)   REFERENCES shifts(shift_code),
    active                  BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by              BIGINT,
    updated_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_by              BIGINT,
    version                 BIGINT        NOT NULL DEFAULT 0,
    company_id              BIGINT        NOT NULL DEFAULT 1,
    CONSTRAINT uq_employees_code UNIQUE (employee_code),
    CONSTRAINT chk_employees_leaving CHECK (date_of_leaving IS NULL OR date_of_leaving >= date_of_joining)
);
CREATE UNIQUE INDEX ux_employees_user ON employees (user_id) WHERE user_id IS NOT NULL;
CREATE INDEX ix_employees_department ON employees (department);

CREATE TABLE employee_skill_matrix (
    id                 BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id        BIGINT       NOT NULL REFERENCES employees(id),
    skill_type         VARCHAR(20)  NOT NULL CHECK (skill_type IN ('MACHINE','OPERATION','CERTIFICATION')),
    machine_id         BIGINT       REFERENCES machines(id),
    operation_id       BIGINT       REFERENCES operations(id),
    skill_name         VARCHAR(80),
    certification_no   VARCHAR(40),
    proficiency_level  SMALLINT     CHECK (proficiency_level BETWEEN 1 AND 5),
    certified_on       DATE,
    expires_on         DATE,
    active             BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by         BIGINT,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by         BIGINT,
    version            BIGINT       NOT NULL DEFAULT 0,
    company_id         BIGINT       NOT NULL DEFAULT 1,
    CONSTRAINT chk_skill_target CHECK (
        (skill_type = 'MACHINE'       AND machine_id IS NOT NULL) OR
        (skill_type = 'OPERATION'     AND operation_id IS NOT NULL) OR
        (skill_type = 'CERTIFICATION' AND skill_name IS NOT NULL))
);
CREATE INDEX ix_skill_employee  ON employee_skill_matrix (employee_id);
CREATE INDEX ix_skill_machine   ON employee_skill_matrix (machine_id)   WHERE machine_id IS NOT NULL;
CREATE INDEX ix_skill_operation ON employee_skill_matrix (operation_id) WHERE operation_id IS NOT NULL;

-- work_hours is generated by PostgreSQL from the check-in/check-out pair (DESIGN section 19.1).
CREATE TABLE attendance (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id      BIGINT       NOT NULL REFERENCES employees(id),
    attendance_date  DATE         NOT NULL,
    shift            VARCHAR(10)  REFERENCES shifts(shift_code),
    check_in         TIMESTAMPTZ,
    check_out        TIMESTAMPTZ,
    status           VARCHAR(10)  NOT NULL DEFAULT 'PRESENT'
                         CHECK (status IN ('PRESENT','ABSENT','HALF_DAY','HOLIDAY','LEAVE')),
    work_hours       NUMERIC(5,2) GENERATED ALWAYS AS (
                         CASE WHEN check_in IS NOT NULL AND check_out IS NOT NULL
                              THEN EXTRACT(EPOCH FROM (check_out - check_in)) / 3600
                              ELSE NULL END) STORED,
    source           VARCHAR(10)  NOT NULL DEFAULT 'MANUAL' CHECK (source IN ('MANUAL','AUTO')),
    remarks          VARCHAR(200),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by       BIGINT,
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by       BIGINT,
    version          BIGINT       NOT NULL DEFAULT 0,
    company_id       BIGINT       NOT NULL DEFAULT 1,
    CONSTRAINT uq_attendance_employee_date UNIQUE (employee_id, attendance_date),
    CONSTRAINT chk_attendance_times CHECK (check_in IS NULL OR check_out IS NULL OR check_out >= check_in)
);
CREATE INDEX ix_attendance_date ON attendance (attendance_date);

CREATE TABLE leave_types (
    id                      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    leave_code              VARCHAR(10)  NOT NULL,
    name                    VARCHAR(40)  NOT NULL,
    max_days_per_year       SMALLINT     CHECK (max_days_per_year >= 0),
    carry_forward           BOOLEAN      NOT NULL DEFAULT FALSE,
    max_carry_forward_days  SMALLINT     NOT NULL DEFAULT 0 CHECK (max_carry_forward_days >= 0),
    paid                    BOOLEAN      NOT NULL DEFAULT TRUE,
    active                  BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by              BIGINT,
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by              BIGINT,
    version                 BIGINT       NOT NULL DEFAULT 0,
    company_id              BIGINT       NOT NULL DEFAULT 1,
    CONSTRAINT uq_leave_types_code UNIQUE (leave_code)
);

