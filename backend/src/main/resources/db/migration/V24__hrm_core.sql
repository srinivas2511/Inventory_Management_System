-- R13 HRM core: shifts, employees, skill matrix, attendance, leave types/balances/applications, training,
-- HR permissions and the HR_MANAGER role. Every table carries the DESIGN section 1.1 standard columns.
SET search_path = ims;

CREATE TABLE shifts (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shift_code     VARCHAR(10)  NOT NULL,
    name           VARCHAR(60)  NOT NULL,
    start_time     TIME         NOT NULL,
    end_time       TIME         NOT NULL,
    grace_minutes  SMALLINT     NOT NULL DEFAULT 0 CHECK (grace_minutes >= 0),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by     BIGINT,
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by     BIGINT,
    version        BIGINT       NOT NULL DEFAULT 0,
    company_id     BIGINT       NOT NULL DEFAULT 1,
    CONSTRAINT uq_shifts_code UNIQUE (shift_code)
);

